-- Initial PostgreSQL target for the portal's existing SQLite schema.
-- Import explicit IDs and then advance each identity sequence before cutover.
BEGIN;

CREATE TABLE orgs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE,
    code text NOT NULL UNIQUE,
    key_limit integer NOT NULL DEFAULT 10,
    enabled integer NOT NULL DEFAULT 1,
    admin_hash text,
    created_at bigint NOT NULL
);

CREATE TABLE people (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id bigint NOT NULL REFERENCES orgs(id),
    phone text NOT NULL,
    name text NOT NULL DEFAULT '',
    created_at bigint NOT NULL,
    rx_archived bigint NOT NULL DEFAULT 0,
    tx_archived bigint NOT NULL DEFAULT 0,
    dev_limit integer,
    UNIQUE (org_id, phone)
);

CREATE TABLE assignments (
    slot integer PRIMARY KEY,
    person_id bigint NOT NULL REFERENCES people(id),
    label text NOT NULL DEFAULT '',
    assigned_at bigint NOT NULL,
    last_download_at bigint,
    downloads bigint NOT NULL DEFAULT 0
);
CREATE INDEX idx_assign_person ON assignments(person_id);

CREATE TABLE audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts bigint NOT NULL,
    actor text NOT NULL,
    org_id bigint,
    action text NOT NULL,
    details text NOT NULL DEFAULT ''
);

CREATE TABLE attempts (ts bigint NOT NULL, ip text NOT NULL, kind text NOT NULL);
CREATE INDEX idx_attempts ON attempts(kind, ts);

CREATE TABLE captchas (id text PRIMARY KEY, answer text NOT NULL, ts bigint NOT NULL);

COMMIT;
